/**
 * Modelos para dados de endereço e CEP
 */

/**
 * Resposta da API ViaCEP
 */
export interface ViaCepResponse {
  cep: string;
  logradouro: string;
  complemento: string;
  bairro: string;
  localidade: string;
  uf: string;
  ibge: string;
  gia: string;
  ddd: string;
  siafi: string;
  erro?: boolean; // Retornado quando CEP não existe
}

/**
 * Modelo de endereço normalizado para uso na aplicação
 */
export interface Endereco {
  cep: string;
  logradouro: string;
  numero?: string;
  complemento?: string;
  bairro: string;
  cidade: string;
  estado: string;
  uf: string;
  ibge?: string;
  ddd?: string;
}

